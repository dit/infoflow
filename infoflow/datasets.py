def coupled_logistic(n=2000, coupling=None, r=4.0, noise_std=0.0, seed=None, burn_in=200):
    """
    Coupled logistic maps ``x_i <- (1 - e_i) f(x_i) + sum_j C[i, j] f(x_j)``.

    ``f(x) = r x (1 - x)``; ``e_i = sum_j C[i, j]``. Default: two maps with
    0 -> 1 coupling 0.2.
    """
    C = np.array([[0.0, 0.0], [0.2, 0.0]]) if coupling is None else np.asarray(coupling, dtype=float)
    P = len(C)
    rng = _rng(seed)
    x = np.zeros((n + burn_in, P))
    x[0] = rng.uniform(0.1, 0.9, size=P)
    e = C.sum(axis=1)
    for t in range(1, n + burn_in):
        f = r * x[t - 1] * (1 - x[t - 1])
        x[t] = (1 - e) * f + C @ f
        if noise_std:
            x[t] = np.clip(x[t] + rng.normal(scale=noise_std, size=P), 1e-9, 1 - 1e-9)
    return x[burn_in:]


def tent_ring_coupling(e_a, e_b=None, e_c=None, e_d=None):
    """
    The coupling matrix of four maps with A -> B, B -> C, B -> D, C -> A, D -> A.

    Processes are ordered (A, B, C, D); ``C[i, j]`` couples ``j`` into ``i``. Each
    node's coupling `e_*` defaults to `e_a`; A's is split equally between C and D.
    """
    e_b, e_c, e_d = (e_a if e is None else e for e in (e_b, e_c, e_d))
    C = np.zeros((4, 4))
    C[0, 2] = C[0, 3] = e_a / 2
    C[1, 0], C[2, 1], C[3, 1] = e_b, e_c, e_d
    return C


def _minimal_period(x, max_period=256, tol=1e-9, window=500):
    tail = x[-window:]
    for p in range(1, min(max_period, len(tail) // 2) + 1):
        if np.max(np.abs(tail[p:] - tail[:-p])) < tol:
            return p
    return None


def coupled_tent(n=2000, slopes=(1.9, 1.9), coupling=None, seed=None, burn_in=3000, symbols=True, period=None):
    """
    Coupled tent maps ``x_i <- (1 - e_i) f_i(x_i) + sum_j C[i, j] f_j(x_j)``.

    ``f_i(x) = s_i min(x, 1 - x)`` with slope ``s_i = slopes[i]``; ``e_i = sum_j C[i, j]``.
    Default: two maps with 0 -> 1 coupling 0.2 (see :func:`tent_ring_coupling` for a
    four-map ring). With `symbols`, the generating partition at 1/2 is returned as
    integer symbols (``x >= 1/2``); otherwise the states.

    Slopes must be below 2: the slope-2 map loses a bit per step and collapses to 0 in
    floating point. If `period` is given, the orbit after `burn_in` must be periodic
    with exactly that minimal period, or a RuntimeError is raised: periodic windows of
    coupled maps are narrow, and a change in the numerics can move them.
    """
    s = np.asarray(slopes, dtype=float)
    if np.any(s <= 0) or np.any(s >= 2):
        raise ValueError("slopes must lie in (0, 2)")
    P = len(s)
    if coupling is None:
        C = np.zeros((P, P))
        C[1, 0] = 0.2
    else:
        C = np.asarray(coupling, dtype=float)
    rng = _rng(seed)
    x = np.zeros((n + burn_in, P))
    x[0] = rng.uniform(0.1, 0.9, size=P)
    e = C.sum(axis=1)
    for t in range(1, n + burn_in):
        f = s * np.minimum(x[t - 1], 1 - x[t - 1])
        x[t] = (1 - e) * f + C @ f
    x = x[burn_in:]
    if period is not None:
        found = _minimal_period(x)
        if found != period:
            raise RuntimeError(f"expected a period-{period} orbit after burn-in, found {found or 'none'}")
    return (x >= 0.5).astype(np.int64) if symbols else x


def lorenz96(n=1000, n_vars=10, forcing=10.0, dt=0.1, substeps=10, noise_std=0.1, seed=None, burn_in=200):
    """
    The Lorenz-96 system :cite:`Lorenz1996`, the standard nonlinear benchmark of the
    neural Granger-causality literature :cite:`Tank2022`.

    :math:`\\dot x_i = (x_{i+1} - x_{i-2}) x_{i-1} - x_i + F` on a ring, integrated by
    fourth-order Runge--Kutta with `substeps` steps per sample of spacing `dt`, plus
    Gaussian observation noise of standard deviation `noise_std`. Each variable's
    parents are its neighbours ``i - 2``, ``i - 1``, ``i + 1`` (and itself); the forcing
    `F` moves the dynamics from periodic (small) to strongly chaotic (``F >= 8``).
    :func:`~infoflow.benchmarks.lorenz96_graph` gives the ground-truth graph.
    """
    rng = _rng(seed)
    h = dt / substeps

    def f(x):
        return (np.roll(x, -1) - np.roll(x, 2)) * np.roll(x, 1) - x + forcing

    x = forcing + rng.normal(scale=0.01, size=n_vars)
    out = np.empty((n + burn_in, n_vars))
    for t in range(n + burn_in):
        for _ in range(substeps):
            k1 = f(x)
            k2 = f(x + 0.5 * h * k1)
            k3 = f(x + 0.5 * h * k2)
            k4 = f(x + h * k3)
            x = x + h * (k1 + 2 * k2 + 2 * k3 + k4) / 6
        out[t] = x
    out = out[burn_in:]
    return out + noise_std * rng.normal(size=out.shape) if noise_std else out


def noisy_eca(n=5000, n_cells=6, rule=90, noise=0.05, seed=None, burn_in=200):
    """
    An elementary cellular automaton on a ring, each update flipped with probability `noise`.

    Cell ``i`` becomes bit ``4 l + 2 c + r`` of `rule` (Wolfram's numbering) for its
    left neighbour ``l``, itself ``c``, and right neighbour ``r`` at the previous step.
    Columns are the cells; each cell's parents are its two neighbours, at delay 1.
    """
    if not 0 <= rule <= 255:
        raise ValueError("rule must be in 0..255")
    rng = _rng(seed)
    table = np.array([(rule >> k) & 1 for k in range(8)], dtype=np.int64)
    x = np.zeros((n + burn_in, n_cells), dtype=np.int64)
    x[0] = rng.integers(0, 2, n_cells)
    for t in range(1, n + burn_in):
        prev = x[t - 1]
        code = 4 * np.roll(prev, 1) + 2 * prev + np.roll(prev, -1)
        x[t] = table[code] ^ (rng.random(n_cells) < noise)
    return x[burn_in:]


def xor_synergy(n=3000, noise=0.0, seed=None):
    """
    Binary: ``y_t = x1_{t-1} xor x2_{t-1}`` (flipped with probability `noise`). Columns (x1, x2, y).
    """
    rng = _rng(seed)
    x1, x2 = rng.integers(0, 2, n), rng.integers(0, 2, n)
    y = np.roll(x1 ^ x2, 1) ^ (rng.random(n) < noise)
    return np.stack([x1, x2, y], axis=1)


def common_driver(n=3000, noise=0.05, seed=None):
    """
    Binary: z drives x at lag 1 and y at lag 2. Columns (x, y, z).

    Bivariately x appears to drive y at lag 1; conditioning on z removes it.
    """
    rng = _rng(seed)
    z = rng.integers(0, 2, n)
    x = np.roll(z, 1) ^ (rng.random(n) < noise)
    y = np.roll(z, 2) ^ (rng.random(n) < noise)
    return np.stack([x, y, z], axis=1)


def switching_coupling(n=4000, block=500, noise=0.1, seed=None):
    """
    Binary pair whose coupling reverses every `block` samples :cite:`Saggioro2020`.

    In even blocks (regime 0) ``y_t = x_{t-1}`` and ``x`` is a fair coin; in odd blocks
    (regime 1) ``x_t = y_{t-1}`` and ``y`` is a fair coin; each copy is flipped with
    probability `noise`. Columns (x, y).
    """
    rng = _rng(seed)
    x, y = rng.integers(0, 2, n), rng.integers(0, 2, n)
    for t in range(1, n):
        flip = int(rng.random() < noise)
        if (t // block) % 2 == 0:
            y[t] = x[t - 1] ^ flip
        else:
            x[t] = y[t - 1] ^ flip
    return np.stack([x, y], axis=1)


def chain(n=3000, noise=0.1, seed=None):
    """
    Binary chain a -> b (lag 1) -> c (lag 2). Columns (a, b, c).
    """
    rng = _rng(seed)
    a = rng.integers(0, 2, n)
    b = np.roll(a, 1) ^ (rng.random(n) < noise)
    c = np.roll(b, 2) ^ (rng.random(n) < noise)
    return np.stack([a, b, c], axis=1)


def orthogonal_features(n=4000, memory=0.5, noise=0.5, seed=None):
    """
    One i.i.d. Gaussian driver read through two independent features. Columns (x0, x1, x2).

    ``x1`` responds to the sign of ``x0`` and ``x2`` to whether ``|x0|`` exceeds
    0.674 (its quartile, so each feature is a fair coin), both at lag 1 with their
    own AR(1) memory. For a symmetric driver the sign and the magnitude are
    independent, so ``x1`` and ``x2`` are independent processes: both edges from
    ``x0`` are intrinsic, and there is no flow of any kind between ``x1`` and ``x2``
    even though they share a driver.
    """
    rng = _rng(seed)
    x0 = rng.normal(size=n)
    sign = np.where(x0 > 0, 1.0, -1.0)
    large = np.where(np.abs(x0) > 0.674, 1.0, -1.0)
    x1, x2 = np.zeros(n), np.zeros(n)
    for t in range(1, n):
        x1[t] = memory * x1[t - 1] + sign[t - 1] + noise * rng.normal()
        x2[t] = memory * x2[t - 1] + large[t - 1] + noise * rng.normal()
    return np.stack([x0, x1, x2], axis=1)


def spiking_glm(
    n=20000,
    weights=None,
    delays=None,
    baseline=0.02,
    refractory=2,
    adaptation=0.0,
    tau_adapt=50,
    dt=0.005,
    seed=None,
    burn_in=500,
):
    """
    A Bernoulli-GLM network of spiking neurons with known delayed couplings.

    In bin ``t`` neuron ``i`` spikes with probability
    :math:`\\sigma(\\mathrm{logit}(b) + \\sum_j W_{ij} s_j(t - D_{ij}) - a\\,A_i(t))`,
    and never within `refractory` bins of its own last spike; :math:`A_i` is an
    exponentially decaying trace (time constant `tau_adapt` bins) of its own spikes,
    so ``adaptation`` gives each neuron a long history dependence.

    Parameters
    ----------
    n : int
        Number of bins.
    weights : array_like, None
        ``weights[i, j]`` is the effect (in logits) of neuron ``j`` on ``i``. Default:
        the chain 0 -> 1 -> 2 with weight 4.
    delays : array_like, None
        ``delays[i, j]`` in bins (default 3 for 0 -> 1 and 5 for 1 -> 2).
    baseline : float
        Spike probability per bin without input.
    refractory, adaptation, tau_adapt : float
    dt : float
        Bin width of the returned spike times.

    Returns
    -------
    spikes : SpikeTrains
        Spike times at bin centres, so that binning at `dt` recovers the bins.
    edges : list of (source, target, delay)
        The true couplings.
    """
    from .spikes import SpikeTrains

    rng = _rng(seed)
    if weights is None:
        weights = np.zeros((3, 3))
        weights[1, 0] = weights[2, 1] = 4.0
        delays = np.zeros((3, 3), dtype=int) if delays is None else delays
        delays[1, 0], delays[2, 1] = 3, 5
    W = np.asarray(weights, dtype=float)
    P = W.shape[0]
    D = np.ones((P, P), dtype=int) if delays is None else np.asarray(delays, dtype=int)
    total = n + burn_in
    s = np.zeros((total, P), dtype=np.int64)
    last = np.full(P, -(10**9))
    trace = np.zeros(P)
    decay = np.exp(-1.0 / tau_adapt)
    rows, cols = np.nonzero(W)
    base = np.log(baseline / (1 - baseline))
    for t in range(total):
        drive = np.full(P, base) - adaptation * trace
        for i, j in zip(rows, cols, strict=True):
            if t - D[i, j] >= 0:
                drive[i] += W[i, j] * s[t - D[i, j], j]
        p = 1.0 / (1.0 + np.exp(-drive))
        p[t - last <= refractory] = 0.0
        s[t] = rng.random(P) < p
        last[s[t] == 1] = t
        trace = trace * decay + s[t]
    s = s[burn_in:]
    times = [(np.flatnonzero(s[:, i]) + 0.5) * dt for i in range(P)]
    edges = [(int(j), int(i), int(D[i, j])) for i, j in zip(rows, cols, strict=True)]
    return SpikeTrains(times, dt=dt, t_start=0.0, t_stop=n * dt), edges
