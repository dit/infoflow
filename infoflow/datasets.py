def _rng(seed):
    return np.random.default_rng(seed)


def var_process(n, coefficients, noise_std=0.1, seed=None, burn_in=200):
    """
    A vector autoregressive process ``x_t = sum_k A_k x_{t-k} + noise``.

    Parameters
    ----------
    n : int
    coefficients : array_like
        Shape (order, processes, processes); ``coefficients[k-1][i, j]`` is the
        effect of process ``j`` at lag ``k`` on process ``i``.
    noise_std : float
    seed : int, None
    burn_in : int
    """
    A = np.asarray(coefficients, dtype=float)
    order, P, _ = A.shape
    rng = _rng(seed)
    x = np.zeros((n + burn_in, P))
    for t in range(order, n + burn_in):
        x[t] = sum(A[k] @ x[t - k - 1] for k in range(order)) + rng.normal(scale=noise_std, size=P)
    return x[burn_in:]


def mute_network(n=2000, seed=None, burn_in=200):
    """
    The five-process network of the MuTE toolbox paper :cite:`Montalto2014` (after
    Baccalá & Sameshima), as generated by IDTxl.

    Couplings (source -> target, lag): 0 -> 1 (2, nonlinear), 0 -> 2 (3),
    0 -> 3 (2, nonlinear), 3 -> 4 (1), 4 -> 3 (1). Each process also depends on
    its own past as in the original equations.
    """
    rng = _rng(seed)
    N = n + burn_in
    x = np.zeros((N, 5))
    w = rng.normal(size=(N, 5))
    r2 = np.sqrt(2)
    for t in range(3, N):
        x[t, 0] = 0.95 * r2 * x[t - 1, 0] - 0.9025 * x[t - 2, 0] + w[t, 0]
        x[t, 1] = 0.5 * x[t - 2, 0] ** 2 + w[t, 1]
        x[t, 2] = -0.4 * x[t - 3, 0] + w[t, 2]
        x[t, 3] = -0.5 * x[t - 2, 0] ** 2 + 0.25 * r2 * x[t - 1, 3] + 0.25 * r2 * x[t - 1, 4] + w[t, 3]
        x[t, 4] = -0.25 * r2 * x[t - 1, 3] + 0.25 * r2 * x[t - 1, 4] + w[t, 4]
    return x[burn_in:]


