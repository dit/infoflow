"""
The network as one generative model, composed from its machines.

Each node with no parents is a *source*, generated by its ε-machine; every other
node is *driven*, generated by its joint-input ε-transducer reading its parents'
symbols at their delays. Every delay is at least one step, so each transducer reads
only the past and feedback loops are well defined: a step updates every component
at once from the previous symbols.

The product is exact only if a node's present is independent of the other nodes'
presents given its own past and its parents' pasts. Coarse-grained deterministic
systems (coupled maps observed through a partition) generally violate this;
:meth:`NetworkModel.adequacy` measures the violation on held-out data.
"""

import itertools

import numpy as np
import xarray as xr
from dit.inference._symbols import as_generator

from .data import DiscreteData, as_trials

__all__ = ("NetworkModel",)


def _rows(machine, transducer):
    """
    Unifilar transition tables: ``key -> (symbols, probs, next states)``.

    For an ε-machine the key is the state; for a transducer, ``(state, input)``.
    """
    from sofic.graph import ATTR_EMISSION, ATTR_OUTPUT, ATTR_PROB, ATTR_SYMBOL

    rows = {}
    for state in machine.states():
        for tr in machine.graph.out_transitions(state):
            prob = float(tr.data[ATTR_PROB])
            if prob <= 0:
                continue
            key = (state, tr.data[ATTR_SYMBOL]) if transducer else state
            symbol = tr.data[ATTR_OUTPUT] if transducer else tr.data[ATTR_EMISSION]
            rows.setdefault(key, []).append((symbol, prob, tr.target))
    return {
        key: (
            [r[0] for r in options],
            np.array([r[1] for r in options]) / sum(r[1] for r in options),
            [r[2] for r in options],
        )
        for key, options in rows.items()
    }


class _Component:
    """
    One node's generator: an ε-machine (no parents) or a transducer (parents).
    """

    def __init__(self, machine, parents=()):
        self.machine = machine
        self.parents = list(parents)
        self.transducer = bool(self.parents)
        self.rows = _rows(machine, self.transducer)
        self.states = list(machine.states())
        initial = {k: float(v) for k, v in machine.initial_distribution.items() if float(v) > 0}
        total = sum(initial.values())
        self.initial = (list(initial), np.array(list(initial.values())) / total)
        if self.transducer:
            pooled = {}
            for (state, _), (symbols, probs, targets) in self.rows.items():
                for sym, p, nxt in zip(symbols, probs, targets, strict=True):
                    pooled.setdefault(state, {}).setdefault((sym, nxt), []).append(p)
            n_inputs = {state: len({u for (s, u) in self.rows if s == state}) for state in pooled}
            self.pooled = {
                state: (
                    [k[0] for k in options],
                    np.array([sum(v) / n_inputs[state] for v in options.values()]),
                    [k[1] for k in options],
                )
                for state, options in pooled.items()
            }

    def options(self, state, u=None):
        """
        ``(symbols, probs, next states)`` from `state` (on input `u`), falling back to
        the input-pooled row when the state never saw `u`.
        """
        if not self.transducer:
            return self.rows[state]
        row = self.rows.get((state, u))
        return row if row is not None else self.pooled[state]

    def lookup(self, state, u=None):
        """
        The observed row only (None if the state never saw `u`), for scoring.
        """
        return self.rows.get((state, u) if self.transducer else state)


def count_forbidden(machine, trials):
    """
    Observed symbols that an ε-machine assigns probability zero once synchronized.

    Each forbidden symbol resynchronizes the tracker. A machine reconstructed with too
    short a history can be confidently wrong (e.g. a deterministic cycle for a process
    whose period needs a longer history to resolve); this counts how often.
    """
    comp = _Component(machine)
    n = 0
    for seq in trials:
        possible = set(comp.states)
        for obs in seq:
            nxt = set()
            for state in possible:
                row = comp.lookup(state)
                if row is not None and obs in row[0]:
                    nxt.add(row[2][row[0].index(obs)])
            if not nxt:
                n += len(possible) == 1
                nxt = set(comp.states)
            possible = nxt
    return int(n)


class NetworkModel:
    """
    The composed generative model of a network's machine layer.

    Attributes
    ----------
    names : list of str
    roles : dict
        ``name -> 'source' | 'driven'``.
    parents : dict
        ``name -> [(parent name, delay), ...]`` for driven nodes.
    max_composed_states : int
        Largest explicit product HMM that :meth:`to_hmm` builds.
    """

    def __init__(self, names, components, baselines, omnibus_te=None, max_composed_states=4096, symbols=None):
        self.names = list(names)
        self._components = components
        self._baselines = baselines
        self.roles = {n: ("driven" if c.transducer else "source") for n, c in zip(self.names, components, strict=True)}
        self.parents = {
            n: [(self.names[p], d) for p, d in c.parents]
            for n, c in zip(self.names, components, strict=True)
            if c.transducer
        }
        self.omnibus_te = np.full(len(self.names), np.nan) if omnibus_te is None else np.asarray(omnibus_te)
        self.max_composed_states = int(max_composed_states)
        self._symbols = symbols if symbols is not None else [[0, 1]] * len(self.names)
        reads = [0] * len(self.names)
        for c in components:
            for p, d in c.parents:
                reads[p] = max(reads[p], d)
        self._depth = reads

    @classmethod
    def from_layer(cls, layer):
        """
        Build the model from a :class:`~infoflow.machines.MachineLayer`.

        Raises ValueError when the layer cannot define one: inputs other than the
        nodes' present symbols, a zero delay, or a node without a machine.
        """
        s = layer.settings
        if s.get("symbols") != "present" or s.get("input_symbols") != "present":
            raise ValueError("the composed model needs symbols='present' and input_symbols='present'")
        names = [str(n) for n in layer.dataset.coords["node"].values]
        index = {n: i for i, n in enumerate(names)}
        components, baselines = [], []
        for name in names:
            baselines.append(_Component(layer.nodes[name]) if name in layer.nodes else None)
            if name in layer.targets:
                parents = [(index[p], int(d)) for p, d in layer.inputs[name]["parents"]]
                if any(d < 1 for _, d in parents):
                    raise ValueError(f"{name} reads a parent at delay 0; the model needs every delay >= 1")
                components.append(_Component(layer.targets[name], parents))
            elif ("target", name) in layer.skipped:
                raise ValueError(f"{name} has parents but no target transducer ({layer.skipped[('target', name)]})")
            elif name in layer.nodes:
                components.append(baselines[-1])
            else:
                raise ValueError(f"{name} has no machine ({layer.skipped.get(('node', name), 'not fitted')})")
        symbols = [sorted({sym for row in b.rows.values() for sym in row[0]}) if b else [0] for b in baselines]
        return cls(
            names,
            components,
            baselines,
            omnibus_te=layer.dataset["target_omnibus_te"].values,
            max_composed_states=s.get("max_composed_states", 4096),
            symbols=symbols,
        )

    # -- simulation ---------------------------------------------------------------

    def _initial_states(self, rng):
        return [c.initial[0][rng.choice(len(c.initial[0]), p=c.initial[1])] for c in self._components]

    def _run(self, n, rng, burn_in):
        P = len(self.names)
        D = max(1, *self._depth)
        total = D + burn_in + n
        x = np.zeros((total, P), dtype=np.int64)
        for p in range(P):
            x[:D, p] = rng.choice(self._symbols[p], size=D)
        states = self._initial_states(rng)
        draws = rng.random((total, P))
        for t in range(D, total):
            for j, c in enumerate(self._components):
                u = tuple(int(x[t - d, p]) for p, d in c.parents) if c.transducer else None
                symbols, probs, targets = c.options(states[j], u)
                k = min(int(np.searchsorted(np.cumsum(probs), draws[t, j])), len(probs) - 1)
                x[t, j] = symbols[k]
                states[j] = targets[k]
        return x[D + burn_in :], states, x[-max(D, 1) :]

    def simulate(self, n, seed=None, burn_in=1000):
        """
        ``n`` steps of symbols, shape ``(n, processes)``, after `burn_in` steps.

        Every component steps at once; driven nodes read their parents' symbols at
        their delays. A transducer state that never saw an input reads the row
        pooled over its inputs.
        """
        return self._run(int(n), as_generator(seed), int(burn_in))[0]

    # -- scoring ------------------------------------------------------------------

    @staticmethod
    def _trials(data):
        if isinstance(data, DiscreteData):
            return [p.T for p in data.present], data.present_offset
        trials = [np.asarray(t, dtype=np.int64) for t in as_trials(data)]
        return trials, np.zeros(trials[0].shape[1], dtype=np.int64)

    def _score(self, trials, offsets):
        P = len(self.names)
        out = {k: np.zeros(P) for k in ("model", "baseline", "n_scored", "n_forbidden")}
        for j in range(P):
            c, b = self._components[j], self._baselines[j]
            start = max([int(offsets[j])] + [int(offsets[p]) + d for p, d in c.parents])
            for x in trials:
                trackers = [(c, set(c.states)), (b, set(b.states))] if b is not None else [(c, set(c.states))]
                for t in range(start, x.shape[0]):
                    obs = int(x[t, j])
                    probs = []
                    for i, (comp, possible) in enumerate(trackers):
                        u = tuple(int(x[t - d, p]) for p, d in comp.parents) if comp.transducer else None
                        synced = len(possible) == 1
                        nxt, prob = set(), None
                        for state in possible:
                            row = comp.lookup(state, u)
                            if row is None or obs not in row[0]:
                                continue
                            k = row[0].index(obs)
                            nxt.add(row[2][k])
                            if synced:
                                prob = float(row[1][k])
                        if not nxt:
                            if synced and i == 0:
                                out["n_forbidden"][j] += 1
                            nxt = set(comp.states)
                        trackers[i] = (comp, nxt)
                        probs.append(prob if synced else None)
                    scored = [p for p in probs if p is not None]
                    if len(scored) == len(probs):
                        out["model"][j] -= np.log2(scored[0])
                        if b is not None:
                            out["baseline"][j] -= np.log2(scored[1])
                        out["n_scored"][j] += 1
        return out

    def log_loss(self, data):
        """
        Bits per symbol of each node under the model and under its own ε-machine.

        ε-machines and ε-transducers are unifilar, so once the observed symbols have
        synchronized a component its state is determined and the joint likelihood
        is a sum of per-node terms. Steps before both the node's component and its
        baseline ε-machine synchronize are skipped; a symbol the model forbids is
        counted in ``n_forbidden`` and resynchronizes the component.

        Parameters
        ----------
        data : DiscreteData, or (samples, processes) integer array / Trials of symbol codes

        Returns
        -------
        xarray.Dataset
            Over ``(node,)``: ``model_bits``, ``baseline_bits``, ``improvement``
            (baseline minus model: an estimate of the collective transfer entropy
            from all parents), ``omnibus_te`` (the skeleton's collective TE, for
            comparison), ``n_scored``, ``n_forbidden``.
        """
        trials, offsets = self._trials(data)
        out = self._score(trials, offsets)
        n = np.maximum(out["n_scored"], 1)
        model, baseline = out["model"] / n, out["baseline"] / n
        has_base = np.array([b is not None for b in self._baselines])
        baseline = np.where(has_base, baseline, np.nan)
        return xr.Dataset(
            {
                "model_bits": (("node",), model),
                "baseline_bits": (("node",), baseline),
                "improvement": (("node",), baseline - model),
                "omnibus_te": (("node",), self.omnibus_te),
                "n_scored": (("node",), out["n_scored"].astype(np.int64)),
                "n_forbidden": (("node",), out["n_forbidden"].astype(np.int64)),
            },
            coords={"node": self.names},
        )

    def adequacy(self, data, n_sim=19, alpha=0.05, seed=None):
        """
        Parametric-bootstrap check of the factorization on (held-out) data.

        Each node's log-loss on `data` is compared with its log-loss on `n_sim`
        simulations from the model with the same trial lengths. A node whose observed
        loss exceeds what the model expects of itself is flagged: its present depends
        on something the product of machines leaves out.

        Returns
        -------
        xarray.Dataset
            Over ``(node,)``: ``observed``, ``expected`` (mean simulated loss), ``gap``,
            ``pvalue`` (one-sided), ``flagged``.
        """
        rng = as_generator(seed)
        trials, _ = self._trials(data)
        observed = self.log_loss(data)["model_bits"].values
        null = np.array(
            [
                self.log_loss([self.simulate(len(x), seed=rng) for x in trials])["model_bits"].values
                for _ in range(n_sim)
            ]
        )
        pvalue = (1 + np.sum(null >= observed[None, :] - 1e-12, axis=0)) / (1 + n_sim)
        expected = null.mean(axis=0)
        return xr.Dataset(
            {
                "observed": (("node",), observed),
                "expected": (("node",), expected),
                "gap": (("node",), observed - expected),
                "pvalue": (("node",), pvalue),
                "flagged": (("node",), pvalue < alpha),
            },
            coords={"node": self.names},
        )

    # -- explicit composition ---------------------------------------------------

    def to_hmm(self, seed=0):
        """
        The explicit product HMM, emitting the tuple of every node's symbol.

        A state is every component's state plus the last few symbols of each node
        that some transducer reads at a delay (a shift register as deep as the
        largest delay). Only the recurrent class reached from a simulated state is
        built.

        Raises
        ------
        ValueError
            When the class has more than `max_composed_states` states.
        """
        from sofic.generators.mealy import MealyHMM

        rng = as_generator(seed)
        _, states, last = self._run(0, rng, burn_in=200)
        buffers = tuple(tuple(int(last[-1 - k, p]) for k in range(self._depth[p])) for p in range(len(self.names)))
        start = (tuple(states), buffers)
        edges, seen, frontier = {}, {start}, [start]
        while frontier:
            state = frontier.pop()
            comp_states, buffers = state
            options = []
            for j, c in enumerate(self._components):
                u = tuple(buffers[p][d - 1] for p, d in c.parents) if c.transducer else None
                symbols, probs, targets = c.options(comp_states[j], u)
                options.append(list(zip(symbols, probs, targets, strict=True)))
            out = {}
            for combo in itertools.product(*options):
                emission = tuple(int(sym) for sym, _, _ in combo)
                prob = float(np.prod([p for _, p, _ in combo]))
                new_buffers = tuple(
                    ((emission[p], *buffers[p][: self._depth[p] - 1]) if self._depth[p] else ())
                    for p in range(len(self.names))
                )
                nxt = (tuple(t for _, _, t in combo), new_buffers)
                out[(nxt, emission)] = out.get((nxt, emission), 0.0) + prob
                if nxt not in seen:
                    seen.add(nxt)
                    if len(seen) > self.max_composed_states:
                        raise ValueError(f"the composed model exceeds max_composed_states={self.max_composed_states}")
                    frontier.append(nxt)
            edges[state] = out
        labels = {state: i for i, state in enumerate(sorted(seen, key=repr))}
        hmm = MealyHMM(
            observation_alphabet=frozenset(e for out in edges.values() for _, e in out),
            initial_distribution={labels[start]: 1.0},
        )
        for state in labels.values():
            hmm.graph.add_state(state)
        for state, out in edges.items():
            for (nxt, emission), prob in out.items():
                if prob > 0:
                    hmm.add_transition(labels[state], labels[nxt], emission, prob)
        return hmm

    def pair_generator(self, hmm, source, target):
        """
        `hmm` (from :meth:`to_hmm`) projected onto the ``(source, target)`` symbol pair.
        """
        from sofic.generators.mealy import MealyHMM
        from sofic.graph import ATTR_EMISSION, ATTR_PROB

        s, t = self.names.index(source), self.names.index(target)
        merged = {}
        for state in hmm.states():
            for tr in hmm.graph.out_transitions(state):
                e = tr.data[ATTR_EMISSION]
                key = (state, tr.target, (e[s], e[t]))
                merged[key] = merged.get(key, 0.0) + float(tr.data[ATTR_PROB])
        pair = MealyHMM(
            observation_alphabet=frozenset(k[2] for k in merged), initial_distribution=dict(hmm.initial_distribution)
        )
        for state in hmm.states():
            pair.graph.add_state(state)
        for (a, b, e), prob in merged.items():
            pair.add_transition(a, b, e, prob)
        return pair

    def exact_flows(self, edges, history=1):
        """
        Exact per-edge flows of the composed model.

        Parameters
        ----------
        edges : list of (source name, target name, delay)
        history : int
            Window length; each edge uses at least its delay.

        Returns
        -------
        dict
            ``(source, target) -> {te, tdmi, intrinsic, synergistic, shared}`` in bits,
            from :mod:`sofic.generators.directional_flow`.
        """
        from sofic.generators import directional_flow as flow

        hmm = self.to_hmm()
        results = {}
        for src, tgt, delay in edges:
            pair = self.pair_generator(hmm, src, tgt)
            h = max(int(history), int(delay))
            te = flow.transfer_entropy(pair, history=h)
            intrinsic = flow.intrinsic_information_flow(pair, history=h)
            shared = flow.shared_information_flow(pair, history=h)
            results[(src, tgt)] = {
                "te": te,
                "tdmi": shared + intrinsic,
                "intrinsic": intrinsic,
                "synergistic": te - intrinsic,
                "shared": shared,
            }
        return results

    def add_exact_flows(self, dataset, network, history=1):
        """
        Add ``model_<layer>`` variables over ``(source, target)`` to `dataset`.

        Returns the reason when the composed model is too large, else None.
        """
        names = self.names
        delay = network.dataset["delay"]
        edges = [
            (names[s], names[t], int(delay.values[s, t]))
            for s, t in sorted(network.edges)
            if str(network.dataset["kind"].values[s, t]) == "parent"
        ]
        try:
            flows = self.exact_flows(edges, history)
        except ValueError as err:
            return str(err)
        P = len(names)
        for layer in ("te", "tdmi", "intrinsic", "synergistic", "shared"):
            values = np.full((P, P), np.nan)
            for (src, tgt), f in flows.items():
                values[names.index(src), names.index(tgt)] = f[layer]
            dataset[f"model_{layer}"] = (("source", "target"), values)
        return None

    def parametric_check(self, network, data, seed=None, compare_kwargs=None, **infer_kwargs):
        """
        Simulate surrogate data from the model, re-infer the network, and compare.

        One surrogate trial is simulated per trial of `data`, with the same lengths,
        and :func:`~infoflow.infer_multiplex` is run on it with `infer_kwargs`. The
        two networks are compared by :func:`~infoflow.compare_networks` (trials are
        the units, so `data` needs several trials).

        Returns
        -------
        surrogate : MultiplexNetwork
        comparison : NetworkComparison
        """
        from .compare import compare_networks
        from .network import infer_multiplex

        rng = as_generator(seed)
        trials, _ = self._trials(data)
        surrogate_data = DiscreteData.from_discrete([self.simulate(len(x), seed=rng) for x in trials], self.names)
        surrogate = infer_multiplex(surrogate_data, names=self.names, prng=rng, **infer_kwargs)
        original = data if isinstance(data, DiscreteData) else DiscreteData.from_discrete(trials, self.names)
        comparison = compare_networks(network, surrogate, original, surrogate_data, prng=rng, **(compare_kwargs or {}))
        return surrogate, comparison
